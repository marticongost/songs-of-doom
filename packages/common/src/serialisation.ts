const ascendInheritanceChain = <T>(
	obj: any,
	visit: (type: Type) => T | undefined,
	fallback: () => T
): T => {
	while (obj) {
		const result = visit(obj.constructor as Type);
		if (result !== undefined) {
			return result;
		}
		obj = Object.getPrototypeOf(obj);
	}
	return fallback();
};
